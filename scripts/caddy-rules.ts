/**
 * The build's Cloudflare Pages rules (`_headers`, `_redirects`) as Caddy directives, for a release Caddy serves instead
 * of Pages: the private test console on the production edge (D217; backend docs/100 §16).
 *
 * Only the forms this site's own generator writes (`src/site/generated.ts`) are accepted — an exact path or a `/*`
 * prefix, a plain target, a status — and anything else is refused, so a rule is never dropped or half-translated.
 * The semantics kept: every matching `_headers` block applies (later ones win a header both set), and the first
 * matching `_redirects` line wins, a 200 being a rewrite. An address that is no file, page or rule is the 404 page.
 */

export interface HeaderRule {
  path: string;
  set: [string, string][];
  remove: string[];
}

export interface RedirectRule {
  from: string;
  to: string;
  status: number;
}

const PATH = /^\/(?:[A-Za-z0-9._~-]+\/)*(?:[A-Za-z0-9._~-]+|\*)?$/;
const STATUSES = new Set([200, 301, 302, 307, 308]);

export function parseHeaders(text: string): HeaderRule[] {
  const rules: HeaderRule[] = [];
  let current: HeaderRule | null = null;
  text.split('\n').forEach((raw, i) => {
    const line = raw.replace(/\r$/, '');
    if (!line.trim() || line.trim().startsWith('#')) return;
    if (!/^\s/.test(line)) {
      const path = line.trim();
      if (!PATH.test(path)) throw new Error(`_headers line ${i + 1}: unsupported path "${path}"`);
      current = { path, set: [], remove: [] };
      rules.push(current);
      return;
    }
    if (!current) throw new Error(`_headers line ${i + 1}: a header before any path`);
    const body = line.trim();
    if (body.startsWith('!')) {
      current.remove.push(body.slice(1).trim());
      return;
    }
    const m = /^([A-Za-z0-9-]+):\s*(.+)$/.exec(body);
    if (!m) throw new Error(`_headers line ${i + 1}: not "Name: value"`);
    current.set.push([m[1] as string, m[2] as string]);
  });
  return rules;
}

export function parseRedirects(text: string): RedirectRule[] {
  return text
    .split('\n')
    .map((l, i) => [l.replace(/\r$/, '').trim(), i + 1] as const)
    .filter(([l]) => l && !l.startsWith('#'))
    .map(([l, n]) => {
      const [from = '', to = '', code = '302', extra] = l.split(/\s+/);
      const status = Number(code);
      if (extra !== undefined || !PATH.test(from) || !PATH.test(to) || to.includes('*') || !STATUSES.has(status)) {
        throw new Error(`_redirects line ${n}: unsupported rule "${l}"`);
      }
      return { from, to, status };
    });
}

const quote = (s: string) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

/** One `route` for the site block: headers first (on every answer), then the first matching rule, a file, or the 404 page. */
export function caddyRoutes(headers: readonly HeaderRule[], redirects: readonly RedirectRule[]): string {
  const lines = ['# Generated by erp-control-web scripts/caddy-release.mjs from the build it sits beside. Do not edit.', 'route {'];
  headers.forEach((r, i) => {
    const matcher = r.path === '/*' ? '' : ` @h${i}`;
    if (matcher) lines.push(`\t@h${i} path ${r.path}`);
    lines.push(`\theader${matcher} {`);
    for (const [name, value] of r.set) lines.push(`\t\t${name} ${quote(value)}`);
    for (const name of r.remove) lines.push(`\t\t-${name}`);
    lines.push('\t}');
  });
  redirects.forEach((r, i) => {
    lines.push(`\t@r${i} path ${r.from}`, `\thandle @r${i} {`);
    if (r.status === 200) lines.push(`\t\trewrite * ${r.to}`, '\t\tfile_server');
    else lines.push(`\t\tredir * ${r.to} ${r.status}`);
    lines.push('\t}');
  });
  lines.push(
    '\t@file file {path} {path}.html {path}/index.html',
    '\thandle @file {',
    '\t\trewrite * {file_match.relative}',
    '\t\tfile_server',
    '\t}',
    '\thandle {',
    '\t\trewrite * /404.html',
    '\t\tfile_server {',
    '\t\t\tstatus 404',
    '\t\t}',
    '\t}',
    '}',
    '',
  );
  return lines.join('\n');
}
